# ------------------------------------------------------------
# 14. Final evidence strength
# ------------------------------------------------------------

def evidence_strength(row):

    assoc = row.get("association_type", "")
    confidence = row.get("association_confidence", "")
    wc = row["worldcover_context"]

    # Direct geometry intersection with mapped OSM feature
    if assoc == "OSM_FEATURE_INTERSECTION":
        if wc == "BUILT_UP":
            return "VERY_HIGH"

        return "HIGH"

    # Nearby feature, but not intersecting
    if assoc == "NEARBY_OSM_INDUSTRIAL_FEATURE":
        return "MEDIUM"

    # WorldCover-only contextual evidence
    if wc in {
        "AGRICULTURAL",
        "NATURAL",
    }:
        return "MEDIUM"

    if wc == "OTHER":
        return "LOW"

    return "LOW"


df["evidence_strength"] = df.apply(
    evidence_strength,
    axis=1,
)


# ------------------------------------------------------------
# 15. Human-readable evidence summary
# ------------------------------------------------------------

def build_evidence_summary(row):

    source = row["source_class_v2"]
    wc = row["worldcover_class"]

    assoc = row.get("association_type", "")
    name = row.get("name", "")
    distance = row.get("distance_km", np.nan)

    if source == "INDUSTRIAL_ASSOCIATED":

        if assoc == "OSM_FEATURE_INTERSECTION":

            if name:
                return (
                    f"Thermal point intersects mapped industrial "
                    f"feature: {name}; WorldCover={wc}"
                )

            return (
                "Thermal point intersects mapped industrial "
                f"feature; WorldCover={wc}"
            )

        if assoc == "NEARBY_OSM_INDUSTRIAL_FEATURE":

            if name and pd.notna(distance):
                return (
                    f"Thermal point is {distance:.3f} km from "
                    f"mapped industrial feature: {name}; "
                    f"WorldCover={wc}"
                )

            return (
                "Thermal point is near mapped industrial "
                f"feature; WorldCover={wc}"
            )

    if source == "AGRICULTURAL":
        return (
            "No strong mapped industrial association; "
            f"WorldCover={wc}"
        )

    if source == "FOREST_NATURAL":
        return (
            "No strong mapped industrial association; "
            f"WorldCover={wc}"
        )

    if source == "OTHER":
        return (
            "No strong mapped industrial association; "
            f"WorldCover={wc}"
        )

    return "Insufficient evidence"


df["evidence_summary"] = df.apply(
    build_evidence_summary,
    axis=1,
)


