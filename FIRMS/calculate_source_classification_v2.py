# ------------------------------------------------------------
# 8. WorldCover category groups
# ------------------------------------------------------------

def normalize_wc(value):
    if pd.isna(value):
        return "UNKNOWN"

    value = str(value).strip().upper()

    # Forest / natural vegetation
    if value in {
        "TREE_COVER",
        "SHRUBLAND",
        "GRASSLAND",
        "HERBACEOUS_WETLAND",
        "MANGROVES",
        "MOSS_LICHEN",
    }:
        return "NATURAL"

    # Agricultural
    if value == "CROPLAND":
        return "AGRICULTURAL"

    # Built environment
    if value == "BUILT_UP":
        return "BUILT_UP"

    # Other non-vegetation
    if value in {
        "BARE_SPARSE_VEGETATION",
        "PERMANENT_WATER_BODIES",
        "SNOW_ICE",
    }:
        return "OTHER"

    return "UNKNOWN"


df["worldcover_context"] = df["worldcover_class"].apply(
    normalize_wc
)


# ------------------------------------------------------------
# 9. Source classification decision logic
# ------------------------------------------------------------
#
# We deliberately avoid pretending that WorldCover alone can
# classify a thermal event.
#
# Priority:
#
# 1. Strong OSM industrial evidence
#       -> INDUSTRIAL_ASSOCIATED
#
# 2. No industrial evidence + CROPLAND
#       -> AGRICULTURAL
#
# 3. No industrial evidence + natural vegetation
#       -> FOREST_NATURAL
#
# 4. No industrial evidence + other land cover
#       -> OTHER
#
# 5. Missing/ambiguous evidence
#       -> UNKNOWN
#
# IMPORTANT:
# "INDUSTRIAL_ASSOCIATED" means spatially associated with
# industrial infrastructure. It does NOT mean confirmed fire.
# ------------------------------------------------------------

def classify(row):

    v1_class = str(row[v1_class_col]).upper().strip()

    wc_context = row["worldcover_context"]

    # --------------------------------------------------------
    # Industrial evidence has priority.
    # --------------------------------------------------------

    if "INDUSTRIAL_ASSOCIATED" in v1_class:
        return "INDUSTRIAL_ASSOCIATED"

    # Some versions may use just INDUSTRIAL
    if v1_class == "INDUSTRIAL":
        return "INDUSTRIAL_ASSOCIATED"

    # --------------------------------------------------------
    # WorldCover contextual classification
    # --------------------------------------------------------

    if wc_context == "AGRICULTURAL":
        return "AGRICULTURAL"

    if wc_context == "NATURAL":
        return "FOREST_NATURAL"

    if wc_context == "OTHER":
        return "OTHER"

    if wc_context == "BUILT_UP":
        # Built-up alone is NOT enough to call something industrial.
        return "UNKNOWN"

    return "UNKNOWN"


df["source_class_v2"] = df.apply(
    classify,
    axis=1,
)


# ------------------------------------------------------------
# 10. Confidence / evidence explanation
# ------------------------------------------------------------

def evidence_level(row):

    v1_class = str(row[v1_class_col]).upper().strip()
    wc = row["worldcover_context"]

    if "INDUSTRIAL_ASSOCIATED" in v1_class:
        if wc == "BUILT_UP":
            return "HIGH"

        return "MEDIUM"

    if wc in {
        "AGRICULTURAL",
        "NATURAL",
    }:
        return "MEDIUM"

    if wc == "OTHER":
        return "LOW"

    return "LOW"


df["classification_confidence_v2"] = df.apply(
    evidence_level,
    axis=1,
)


def evidence_reason(row):

    v1_class = str(row[v1_class_col]).upper().strip()
    wc = row["worldcover_context"]

    if "INDUSTRIAL_ASSOCIATED" in v1_class:

        if wc == "BUILT_UP":
            return (
                "OSM industrial association + built-up "
                "WorldCover context"
            )

        return (
            "OSM industrial association; WorldCover "
            f"context={wc}"
        )

    if wc == "AGRICULTURAL":
        return (
            "No strong OSM industrial association; "
            "WorldCover indicates cropland"
        )

    if wc == "NATURAL":
        return (
            "No strong OSM industrial association; "
            "WorldCover indicates natural vegetation"
        )

    if wc == "OTHER":
        return (
            "No strong OSM industrial association; "
            f"WorldCover context={row['worldcover_class']}"
        )

    if wc == "BUILT_UP":
        return (
            "Built-up context detected, but no strong "
            "industrial evidence"
        )

    return "Insufficient contextual evidence"


df["classification_reason"] = df.apply(
    evidence_reason,
    axis=1,
)


